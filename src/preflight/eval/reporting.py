"""Render evaluation documentation solely from machine-readable measured results."""

from decimal import Decimal

from preflight.eval.harness import Evaluation, Gates
from preflight.eval.metrics import Rate

LIMITATIONS = (
    (
        "Synthetic PDFs and fixture extractions measure deterministic "
        "triage, not real-world fraud accuracy or live-model robustness."
    ),
    (
        "Wrong-but-validly-cited bank and amount values can pass when the "
        "model chooses a superseded account or coherent historical quote. "
        "Text presence does not establish semantic association."
    ),
    (
        "Dropped payment fields can leave bank change unverifiable while "
        "other checks still permit PASS. The gap stays visible, but PASS "
        "must not be treated as payment authorization."
    ),
    (
        "Sender display-name/domain and external Reply-To heuristics "
        "cannot establish intent. Legitimate routing services can be false "
        "positives; unrelated attacker domains may evade distance checks."
    ),
    (
        "Uploaded Authentication-Results are untrusted. Passing headers "
        "never establish authenticated sender identity; no receiver trust "
        "integration is provided."
    ),
    (
        "Median/MAD flags legitimate large one-off invoices. Zero-MAD "
        "handling flags even small legitimate increases. Neither method "
        "proves fraud."
    ),
    (
        "No OCR: image-only evidence returns REVIEW. Identifier "
        "syntax/checksums do not establish registration, ownership or bank "
        "existence."
    ),
    (
        "Vendor matching uses an explicit selection or exact extracted "
        "name. No authenticated vendor identity, payment execution or "
        "multi-user access control exists."
    ),
    (
        "Native document parsers run in-process with bounded inputs, not "
        "an isolated CPU/memory sandbox. Local reports retain sensitive "
        "evidence on disk without encryption."
    ),
    (
        "The corpus uses reserved example domains and one vendor template "
        "with varied amounts/noise. Equal strata do not estimate "
        "production prevalence. Wilson intervals assume independent "
        "trials; shared templates violate that assumption, so intervals "
        "are descriptive only."
    ),
    (
        "The regression gate uses point estimates and the same synthetic "
        "seed used for initial calibration. It is a regression alarm, not "
        "a held-out validation claim."
    ),
)


def percent(value: str) -> str:
    """Format a decimal fraction as a human-readable percentage."""
    return f"{Decimal(value) * 100:.2f}%"


def format_rate(value: Rate) -> str:
    """Render undefined denominators explicitly rather than claiming perfect accuracy."""
    if value.value is None:
        return "N/A (0 denominator)"
    assert value.lower is not None and value.upper is not None
    return (
        f"{percent(value.value)} [{percent(value.lower)}, "
        f"{percent(value.upper)}] ({value.numerator}/{value.denominator})"
    )


def markdown(result: Evaluation, gates: Gates) -> str:
    """Generate counts, metrics, representative errors, ablations and honest limits."""
    lines = [
        "# Preflight offline evaluation",
        "",
        (
            "Generated by `python -m preflight.eval` from "
            "`artifacts/eval.json`. Do not edit numbers by hand."
        ),
        "",
        (
            f"Seed: **{result.seed}**. Cases: **{result.case_count}**. All runs "
            f"use FakeExtractor, in-memory SQLite and real PDF "
            f"ingestion/citation validation. No network or trained model is "
            f"used."
        ),
        "",
        "## Metric definitions",
        "",
        (
            "A positive is REVIEW or BLOCK. A false negative is a malicious "
            "case receiving PASS. Legitimate reviews, including prudent "
            "reviews for missing data, count as false positives (workflow "
            "friction). Expected verdicts encode ground-truth intent; a "
            "prudent REVIEW can disagree with PASS ground truth without being "
            "a software defect."
        ),
        "",
        (
            "Each attack row compares that attack against the same complete "
            "legitimate pool. Precision is TP/(TP+all legitimate FP); FPR uses "
            "that pool. Benign rows use only their own stratum. Recall is undefined; "
            "precision is zero when positive predictions exist and undefined otherwise. "
            "The reused negative pool "
            "means rows must not be added together. All intervals are Wilson "
            "95%; counts and denominators are shown."
        ),
        "",
        "## Headline comparison",
        "",
        "| System | Precision [95% CI] | Recall [95% CI] | Legitimate FPR [95% CI] |",
        "|---|---|---|---|",
        (
            f"| Full pipeline | {format_rate(result.overall.precision)} | "
            f"{format_rate(result.overall.recall)} | "
            f"{format_rate(result.overall.false_positive_rate)} |"
        ),
        (
            f"| Naive: arithmetic + identifiers | "
            f"{format_rate(result.baseline.precision)} | "
            f"{format_rate(result.baseline.recall)} | "
            f"{format_rate(result.baseline.false_positive_rate)} |"
        ),
        "",
        "## Per-type results",
        "",
        "| Stratum | Precision [95% CI] | Recall [95% CI] | FPR [95% CI] |",
        "|---|---|---|---|",
    ]
    for kind, value in result.per_type.items():
        lines.append(
            f"| {kind} | {format_rate(value.precision)} | "
            f"{format_rate(value.recall)} | "
            f"{format_rate(value.false_positive_rate)} |"
        )
    lines.extend(
        [
            "",
            "## PASS / REVIEW / BLOCK confusion",
            "",
            "Rows are intended verdicts; columns are actual verdicts.",
            "",
            "| Expected | PASS | REVIEW | BLOCK |",
            "|---|---:|---:|---:|",
        ]
    )
    for expected, counts in result.confusion.items():
        lines.append(
            f"| {expected} | {counts['PASS']} | {counts['REVIEW']} | {counts['BLOCK']} |"
        )
    lines.extend(
        [
            "",
            "## Ablation",
            "",
            (
                "Each variant reruns identical cases and baselines with exactly "
                "one check disabled. Loss is in percentage points; zero loss can "
                "reflect redundant checks or low-only findings."
            ),
            "",
            (
                "| Disabled check | Overall recall | Recall lost | Legitimate FPR "
                "| Attack recall losses |"
            ),
            "|---|---:|---:|---:|---|",
        ]
    )
    for name, variant in result.ablations.items():
        losses = (
            "; ".join(
                f"{kind}: {percent(value)}"
                for kind, value in variant.per_attack_recall_lost.items()
                if Decimal(value) != 0
            )
            or "None"
        )
        lines.append(
            f"| {name} | {percent(variant.metrics.recall.value or '0')} | "
            f"{percent(variant.recall_lost)} | "
            f"{percent(variant.metrics.false_positive_rate.value or '0')} | "
            f"{losses} |"
        )
    lines.extend(
        [
            "",
            "## Extraction-noise and miss analysis",
            "",
            (
                "Bank-change attacks deliberately include dropped bank fields and "
                "wrong-but-cited superseded accounts. Inflated invoices also have "
                "a separate wrong_cited_amount stratum selecting a real, coherent "
                "historical quote. OCR substitutions on legitimate invoices and "
                "missing totals measure false-review friction. These errors are "
                "injected in the extractor fixture, not in policy labels."
            ),
            "",
        ]
    )
    for label, malicious in (("False negatives", True), ("False positives", False)):
        errors = [
            item
            for item in result.outcomes
            if item.malicious == malicious
            and ((item.actual == "PASS") if malicious else (item.actual != "PASS"))
        ]
        lines.extend([f"### {label} ({len(errors)})", ""])
        seen: set[tuple[str, str]] = set()
        for item in errors:
            key = (item.kind, item.noise)
            if key in seen:
                continue
            seen.add(key)
            reason = (
                item.explanation
                or ", ".join(item.checks)
                or "No risk signal survived extraction."
            )
            lines.append(
                f"- `{item.id}`: intended {item.expected}, got **{item.actual}**; "
                f"noise `{item.noise}`. {reason}"
            )
        if not errors:
            lines.append("No cases in this category.")
        lines.append("")
    lines.extend(
        [
            "## Fixed CI gates",
            "",
            gates.rationale,
            "",
            (
                f"Calibration seed/cases: "
                f"{gates.calibration_seed}/{gates.calibration_cases}. Limits were "
                f"set from the initial measured run with a small margin. `--check` "
                f"reads the checked-in config and never recalibrates. Only explicit "
                f"`--calibrate` rewrites it."
            ),
            "",
        ]
    )
    lines.extend(
        f"- {kind} recall >= {percent(str(minimum))}."
        for kind, minimum in gates.critical_recall_min.items()
    )
    lines.extend(
        [
            f"- Clean-case FPR <= {percent(str(gates.clean_fpr_max))}.",
            "",
            "## Honest limitations",
            "",
        ]
    )
    lines.extend(f"- {item}" for item in LIMITATIONS)
    lines.extend(
        [
            "",
            "## Reproduction",
            "",
            "```sh",
            "uv sync --locked --group dev",
            "uv run python -m preflight.eval --check",
            "# Initial calibration only, never in CI:",
            "# uv run python -m preflight.eval --calibrate",
            "```",
            "",
            (
                "Runtime is printed separately to preserve byte-identical "
                "JSON/Markdown across repeated runs. The CLI exits nonzero on gate "
                "failure. See README for the separate five-document live-model "
                "smoke test; it is never part of CI."
            ),
            "",
        ]
    )
    return "\n".join(lines)
